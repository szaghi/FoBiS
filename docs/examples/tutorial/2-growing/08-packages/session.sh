# quad becomes a package: a git repository with a tag, listed in an index, added by name to another project,
# published as a release on static hosting, installed for this compiler, audited
quiet 'printf "build/\n.fobis_deps/\n*.tar.gz\n" > .gitignore && git init -q && git add -A && git commit -q -m "quad 0.1.0" && git tag v0.1.0'
quiet 'git clone -q --bare . ~/remotes/quad.git'
show publish 'fobis publish --index ~/my-index/index.toml --source file://$HOME/remotes/quad.git'
show index 'cat ~/my-index/index.toml'
show index-add 'fobis index add mine ~/my-index'
show search 'fobis search --module quad_rules'
show info 'fobis info quad'
quiet 'cp -R "$DOCS_CHAPTER/survey" ~/survey'
show add 'cd ~/survey && fobis add quad'
excerpt dependencies ~/survey/fobos '[dependencies]'
show fetch 'cd ~/survey && fobis fetch'
show build 'cd ~/survey && fobis build --quiet && ./build/survey'
show lock 'cd ~/survey && grep -E "^\\[|resolved|required_by" .fobis_deps/fobos.lock'
show archive 'fobis publish --archive ~/site/quad'
show manifest 'cat ~/site/quad/fortran-releases.toml'
show static 'fobis info ~/site/quad'
measure pkg 'fobis pkg install quad --bin-dir ~/bin'
measure pkg-config 'PKG_CONFIG_PATH=$(fobis pkg path quad --pkgconfig) pkg-config --cflags --libs quad'
show audit 'cd ~/survey && fobis audit'
