# trust without a central server: a mirror listed by the index, an advisory published by the package itself, and
# witnesses (the source and its mirrors agreeing on what a tag names)
quiet 'git clone -q --bare ~/remotes/kinds.git ~/mirror/kinds.git'
quiet 'sed -i "/^source = \"file:\/\/.*\/remotes\/kinds.git\"$/a mirrors = [\"file://$HOME/mirror/kinds.git\"]" ~/lab-index/index.toml'
show entry 'grep -A4 "^\[package.kinds\]" ~/lab-index/index.toml'
show add 'fobis add lab:kinds --semver "^1.0.0" --force'
quiet 'fobis fetch'
quiet 'mv ~/remotes/kinds.git ~/remotes/kinds.git.away && rm -rf .fobis_deps/kinds'
show mirror 'fobis fetch'
quiet 'mv ~/remotes/kinds.git.away ~/remotes/kinds.git'
quiet 'cd ~/src/kinds && cp "$DOCS_CHAPTER/fortran-advisories.toml" . && git add -A && git commit -q -m "advisory KINDS-2026-001" && git push -q ~/remotes/kinds.git main'
show advisories 'fobis audit'
quiet 'cd ~/src/kinds && git checkout -q -b maint-1.1 v1.1.0 && sed -i "s/selected_real_kind(6, 37)/selected_real_kind(6, 307)/" src/kinds.f90 && git commit -q -am "kinds 1.1.1" && git tag v1.1.1 && git push -q ~/remotes/kinds.git v1.1.1 && git checkout -q main'
show still 'fobis fetch --update && fobis audit'
show raise 'fobis add lab:kinds --semver "^1.1.1" --force && fobis fetch && fobis audit'
show witness 'fobis audit --witness'
quiet 'cd ~/src/kinds && git push -q ~/mirror/kinds.git v1.1.1'
show synced 'fobis audit --witness'
quiet 'cd ~/src/kinds && git push -q --force ~/mirror/kinds.git main:refs/tags/v1.1.1'
show moved 'fobis audit --witness'
