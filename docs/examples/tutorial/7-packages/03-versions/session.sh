# kinds publishes a compatible 1.1.0 and an incompatible 2.0.0; solver moves within its range, then across it;
# vectors 0.2.0 requires kinds 1.1, and fetch resolves what dependencies require (minimal version selection)
quiet 'cd ~/src/kinds && git checkout -q v1.0.0 -- . && cp "$DOCS_CHAPTER/kinds-1.1/kinds.f90" src/kinds.f90 && ~/bin/publish kinds v1.1.0'
quiet 'cp "$DOCS_CHAPTER/kinds-2.0/kinds.f90" ~/src/kinds/src/kinds.f90 && ~/bin/publish kinds v2.0.0'
show versions 'fobis info lab:kinds'
show update 'fobis fetch --update'
show locked 'grep -A3 "^\[kinds\]" .fobis_deps/fobos.lock'
show major 'fobis add lab:kinds --semver "^2.0.0" --force'
quiet 'fobis fetch --update'
show broken 'fobis build --quiet'
show back 'fobis add lab:kinds --semver "^1.0.0" --force'
quiet 'sed -i "s|semver=^1.0.0|semver=^1.1.0|" ~/src/vectors/fobos && ~/bin/publish vectors v0.2.0'
quiet 'fobis add lab:vectors --semver "^0.2.0" --force && printf "transitive = true\n" >> fobos'
excerpt transitive fobos '[dependencies]'
show resolved 'fobis fetch --update'
show required 'grep -E "^\[|resolved|required_by" .fobis_deps/fobos.lock'
show run 'fobis build --quiet && ./build/solver'
show conflict 'fobis add lab:kinds --semver "^2.0.0" --force && fobis fetch --update'
quiet 'fobis add lab:kinds --semver "^1.0.0" --force && fobis fetch --update'
