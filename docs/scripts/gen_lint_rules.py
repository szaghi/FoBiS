"""Generate the lint-rule reference pages from the rule registry (single source of truth).

Writes ``docs/lint-rules/index.md``, one ``docs/lint-rules/<ID>.md`` per rule and ``docs/lint-rules/sidebar.json``
(imported by ``.vitepress/config.mts``). The generated files are committed; ``tests/test_lint_docs.py`` fails when
they are stale. Regenerate with::

    python docs/scripts/gen_lint_rules.py
"""

from __future__ import annotations

import json
import os
import sys
import textwrap

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(os.path.dirname(HERE)))  # the repository root, for "import fobis"

from fobis.lint import FAMILIES, RULES  # noqa: E402

OUT_DIR = os.path.join(os.path.dirname(HERE), "lint-rules")
_SEVERITY_BADGE = {"error": "danger", "warning": "warning", "info": "info"}


def _cell(text: str) -> str:
    return text.replace("|", "\\|")


def _block(code: str) -> str:
    return f"```fortran\n{textwrap.dedent(code).strip()}\n```"


def rule_page(rid: str) -> str:
    """Markdown page of rule *rid*."""
    rul = RULES[rid]
    badges = [
        f'<Badge type="{_SEVERITY_BADGE[rul.severity]}" text="{rul.severity}" />',
        '<Badge type="tip" text="enabled by default" />' if rul.default else '<Badge type="info" text="opt-in" />',
    ]
    lines = [
        "---",
        f"title: {rid} {rul.name}",
        "---",
        "",
        "<!-- Generated by docs/scripts/gen_lint_rules.py from the rule registry: do not edit. -->",
        "",
        f"# {rid} `{rul.name}`",
        "",
        " ".join(badges),
        "",
        rul.summary,
        "",
        "## Why",
        "",
        textwrap.dedent(rul.rationale).strip(),
    ]
    if rul.bad:
        lines += ["", "## Reported", "", _block(rul.bad)]
    if rul.good:
        lines += ["", "## Preferred", "", _block(rul.good)]
    lines += [
        "",
        "## Suppressing",
        "",
        "For one occurrence, with the reason on the same line (or alone on the line before the statement):",
        "",
        f"```fortran\n! fobis: ignore[{rid}] <why this occurrence is fine>\n```",
        "",
        f"For the whole project, `ignore = {rid}` in the fobos [`[lint]` section](/cookbook/analysis#choose-the-rules).",
    ]
    if rul.refs:
        lines += [
            "",
            "## References",
            "",
            "Sections of the shipped [knowledge packs](/cookbook/ai-setup#search-the-knowledge-packs) behind this rule:",
            "",
        ]
        lines += [f"- `{ref}` (`fobis kb show {ref}`)" for ref in rul.refs]
    if rul.equivalent:
        lines += [
            "",
            "## Equivalent",
            "",
            f"Fortitude rule `{rul.equivalent}` (see [Lint Rules](/lint-rules/#relation-to-fortitude)).",
        ]
    return "\n".join(lines) + "\n"


def index_page() -> str:
    """Markdown index: one table per family."""
    lines = [
        "---",
        "title: Lint Rules",
        "---",
        "",
        "<!-- Generated by docs/scripts/gen_lint_rules.py from the rule registry: do not edit. -->",
        "",
        "# Lint Rules",
        "",
        f"`fobis lint` has {len(RULES)} rules. Rules marked *default* run unless a selection is given;",
        "*opt-in* rules run only when selected (`--select COR003`, a prefix like `--select COR`, or `ALL`).",
        "Run `fobis lint --explain <ID>` for the same documentation in the terminal. How to run, select and",
        "suppress rules: [Code quality](/cookbook/analysis).",
    ]
    for prefix, family in FAMILIES.items():
        rules = sorted((r for r in RULES.values() if r.family == prefix), key=lambda r: r.id)
        if not rules:
            continue
        lines += [
            "",
            f"## {family} (`{prefix}`)",
            "",
            "| Rule | Name | Severity | Default | Fortitude | Reports |",
            "|------|------|----------|---------|-----------|---------|",
        ]
        for rul in rules:
            lines.append(
                f"| [{rul.id}](/lint-rules/{rul.id}) | `{rul.name}` | {rul.severity} | "
                f"{'yes' if rul.default else 'opt-in'} | {rul.equivalent or '-'} | {_cell(rul.summary)} |"
            )
    lines += [
        "",
        "## Relation to Fortitude",
        "",
        "The generic rules (`COR`, `OBS`, `MDN`, `PRT`, `STY`) are a native reimplementation, in FoBiS's own",
        "words and on its own source analysis, of rules catalogued by [Fortitude](https://fortitude.readthedocs.io/)",
        "(PlasmaFAIR, MIT licence), whose rule set served as the reference. The *Fortitude* column gives the",
        "matching Fortitude code, for users who know it. FoBiS does not depend on Fortitude. The `FOR`, `NUM`,",
        "`OMP`, `ACC`, `MPI` and `PRF` rules are FoBiS's own, distilled from the OpenMP, OpenACC and MPI",
        "specifications and from HPC practice.",
        "",
        "Not reimplemented: Fortitude's formatting rules (line length, whitespace, keyword case, quotes:",
        "formatters own them) and `S263` (a project-configured preference between `dimension(n)` and `x(n)`).",
        "The thresholds of `STY020` and `STY021` are fixed (complexity 10, 8 arguments).",
    ]
    return "\n".join(lines) + "\n"


def sidebar() -> list[dict]:
    """VitePress sidebar for /lint-rules/."""
    groups = [{"text": "Lint Rules", "items": [{"text": "Overview", "link": "/lint-rules/"}]}]
    for prefix, family in FAMILIES.items():
        rules = sorted((r for r in RULES.values() if r.family == prefix), key=lambda r: r.id)
        if rules:
            groups.append(
                {
                    "text": f"{family} ({prefix})",
                    "collapsed": True,
                    "items": [{"text": f"{r.id} {r.name}", "link": f"/lint-rules/{r.id}"} for r in rules],
                }
            )
    return groups


def generate() -> dict[str, str]:
    """Contents of every generated file, keyed by file name (relative to `OUT_DIR`)."""
    files = {"index.md": index_page(), "sidebar.json": json.dumps(sidebar(), indent=2) + "\n"}
    files.update({f"{rid}.md": rule_page(rid) for rid in RULES})
    return files


def main() -> None:
    os.makedirs(OUT_DIR, exist_ok=True)
    files = generate()
    for stale in set(os.listdir(OUT_DIR)) - set(files):
        if stale.endswith(".md") or stale == "sidebar.json":
            os.remove(os.path.join(OUT_DIR, stale))
    for name, content in files.items():
        with open(os.path.join(OUT_DIR, name), "w", encoding="utf-8") as handle:
            handle.write(content)
    print(f"{len(files)} files written to {OUT_DIR}")


if __name__ == "__main__":
    main()
