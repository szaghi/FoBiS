"""Generate the command reference from the command line itself.

Every ``docs/reference/<command>.md`` gets an "All options" section, between ``<!-- cli:begin -->`` and
``<!-- cli:end -->`` markers, listing every option of the command and of its subcommands with its value, default
and help, as ``fobis <command> --help`` prints them. The text around the markers is written by hand and kept; a
page without markers gets the section appended; a command without a page gets one. ``docs/reference/index.md``, the
map of all the commands by area, is generated whole; so are the table of every fobos mode key
(``docs/fobos/index.md``) and the commented user configuration (``docs/reference/configuration.md``).

Usage::

    python docs/scripts/gen_cli_reference.py            # write
    python docs/scripts/gen_cli_reference.py --check    # exit 1 when a page is stale
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

REFERENCE = Path(__file__).resolve().parent.parent / "reference"
BEGIN, END = "<!-- cli:begin -->", "<!-- cli:end -->"
NOTE = "<!-- generated by docs/scripts/gen_cli_reference.py from the command line: do not edit -->"

# the map of the commands: every command must be in one area
AREAS = {
    "Building": ["build", "clean", "run", "install", "rule", "cache", "introspect", "tree", "check"],
    "Dependencies and projects": ["fetch", "fpm", "scaffold", "ecosystem"],
    "Testing": ["test", "doctests", "coverage"],
    "Verifying results": ["case", "provenance", "verify", "matrix", "assess", "diff-run", "bench", "gate", "profile"],
    "Code analysis": ["lint", "review", "query", "modernize", "bindings", "agents-md"],
    "AI assistance": ["llm", "ask", "kb", "testgen", "merge-assist", "commit", "mcp"],
}


FOBOS = REFERENCE.parent / "fobos" / "index.md"
KEYS_BEGIN, KEYS_END = "<!-- keys:begin -->", "<!-- keys:end -->"
CONFIG_BEGIN, CONFIG_END = "<!-- config:begin -->", "<!-- config:end -->"
CONFIG_PATH = "~/.config/fobis/config.ini"
# the commands that read a fobos mode: a mode key is a field of their settings
MODE_COMMANDS = ("build", "clean", "install", "doctests", "rule")
# fields of the settings that are not project settings (command-line plumbing)
NOT_KEYS = {
    "which", "fobos", "fobos_case_insensitive", "mode", "lmodes", "json_output", "build_dir_explicit", "variant",
    "variant_cflags", "variant_lflags", "shadow", "explain", "explain_context", "active_features", "target_filter",
    "examples", "repo", "branch", "tag", "rev", "update", "no_build", "execute", "list", "get", "get_output_name",
    "ford", "gcov_analyzer", "is_ascii_kind_supported", "is_float128_kind_supported", "is_ucs4_kind_supported",
    "only_obj", "only_target", "makefile",
}  # fmt: skip
# keys a mode holds that are not command-line settings, read by the fobos parser itself
OTHER_KEYS = {
    "template": "A `[template-NAME]` section whose keys this mode inherits (its own keys win)",
    "help": "One line describing the mode, shown by `fobis build --lmodes`",
    "externals": "External libraries to detect and link (`mpi hdf5 ...`): their compile and link flags are added",
    "pkgconfig": "Write a pkg-config `.pc` file for the library this mode builds",
    "pkgconfig_name": "Package name in the `.pc` file (default: `[project]` name)",
    "pkgconfig_desc": "Description in the `.pc` file",
    "pkgconfig_url": "URL in the `.pc` file",
    "pkgconfig_req": "`Requires:` line of the `.pc` file",
    "pkgconfig_req_priv": "`Requires.private:` line of the `.pc` file",
    "launcher": "Start the mode's programs through this command (`mpirun -np {ranks}`, `gdb --args`, `valgrind`); "
    "`--launcher` wins, `[test] launcher` applies when the mode has none",
}
# the commands reading a key of OTHER_KEYS, when not build
OTHER_KEY_COMMANDS = {"launcher": ["run", "test"]}


def mode_keys() -> dict[str, tuple[str, list[str]]]:
    """Every key a fobos mode may hold: ``{key: (description, commands that read it)}``. The keys are the fields of
    the settings of the commands that read a mode (``Fobos`` sets a field when a mode key has its name; any other key
    is ignored, silently), plus the keys the fobos parser reads itself."""
    import tempfile

    import typer

    from fobis.cli._app import app
    from fobis.FoBiSConfig import FoBiSConfig

    root = typer.main.get_command(app)
    found: dict[str, tuple[str, list[str]]] = {}
    with tempfile.TemporaryDirectory() as empty:
        cwd = Path.cwd()
        try:
            import os

            os.chdir(empty)  # no fobos here: the settings' defaults only
            for name in MODE_COMMANDS:
                fields = vars(FoBiSConfig(fake_args=[name]).cliargs)
                helps = {p.name: p.help or "" for p in root.commands[name].params}
                for field in fields:
                    if field in NOT_KEYS:
                        continue
                    text, commands = found.get(field, (helps.get(field, ""), []))
                    found[field] = (text or helps.get(field, ""), [*commands, name])
        finally:
            os.chdir(cwd)
    for key, text in OTHER_KEYS.items():
        found.setdefault(key, (text, OTHER_KEY_COMMANDS.get(key, ["build"])))
    return dict(sorted(found.items()))


def keys_section() -> str:
    lines = [KEYS_BEGIN, NOTE, "", "| Key | Read by | Description |", "|---|---|---|"]
    for key, (text, commands) in mode_keys().items():
        read = "all" if set(commands) >= set(MODE_COMMANDS) else ", ".join(commands)
        lines.append(f"| `{key}` | {read} | {_cell(text)} |")
    return "\n".join([*lines, "", KEYS_END])


def _is_group(node) -> bool:
    return isinstance(getattr(node, "commands", None), dict)


def _first_line(text: str | None) -> str:
    """The first paragraph of a help text, on one line, with angle brackets escaped for VitePress."""
    line = (text or "").strip().split("\n\n")[0].replace("\n", " ").strip()
    return line.replace("<", "&lt;").replace(">", "&gt;")


def _cell(text: str) -> str:
    """Text for a table cell: pipes escaped, and angle brackets (VitePress would read ``<mode>`` as a tag)."""
    return text.replace("|", "\\|").replace("\n", " ").replace("<", "&lt;").replace(">", "&gt;")


def _value(param) -> str:
    if param.is_flag or param.count:
        return ""
    name = getattr(param.type, "name", "") or ""
    # the type names change between Typer releases (0.24: text, integer range; 0.27: str, int range)
    for kind, words in (("TEXT", ("text", "str", "string")), ("INTEGER", ("integer", "int")), ("FLOAT", ("float",))):
        if name.replace(" range", "") in words:
            return kind
    return name.upper()


def _default(param) -> str:
    default = param.default
    if param.is_flag or default is None or default == () or default == [] or default is False:
        return ""
    if callable(default):
        return ""
    return f"`{default}`" if default != "" else ""


def options_table(command) -> list[str]:
    """The markdown table of a command's visible options (``--help`` aside)."""
    rows = []
    for param in command.params:
        if param.param_type_name != "option" or getattr(param, "hidden", False):
            continue
        names = ", ".join(f"`{o}`" for o in [*param.opts, *param.secondary_opts] if o != "--help")
        rows.append(f"| {names} | {_value(param)} | {_default(param)} | {_cell(param.help or '')} |")
    arguments = [p for p in command.params if p.param_type_name == "argument"]
    lines = []
    if arguments:
        shown = " ".join(p.name.upper() + ("..." if p.nargs == -1 else "") for p in arguments)  # case: as Typer 0.24
        lines += [f"Arguments: `{shown}`", ""]
    if rows:
        lines += ["| Option | Value | Default | Description |", "|---|---|---|---|", *rows]
    else:
        lines.append("No options.")
    return lines


def section(name: str, command) -> list[str]:
    """The generated "All options" section of command *name*."""
    lines = [BEGIN, NOTE, "", "## All options", ""]
    if _is_group(command):
        for sub_name, sub in sorted(command.commands.items()):
            lines += [f"### `fobis {name} {sub_name}`", "", _first_line(sub.help), ""]
            if _is_group(sub):
                for inner_name, inner in sorted(sub.commands.items()):
                    lines += [f"#### `fobis {name} {sub_name} {inner_name}`", "", _first_line(inner.help), ""]
                    lines += [*options_table(inner), ""]
            else:
                lines += [*options_table(sub), ""]
    else:
        lines += [*options_table(command), ""]
    lines.append(END)
    return lines


def page(name: str, command, current: str | None) -> str:
    """The reference page of command *name*: the hand-written text of *current* with the section replaced."""
    block = "\n".join(section(name, command))
    if current is None:
        return f"# `{name}` command\n\n{_first_line(command.help)}\n\n```bash\nfobis {name} --help\n```\n\n{block}\n"
    if BEGIN in current and END in current:
        head, rest = current.split(BEGIN, 1)
        tail = rest.split(END, 1)[1]
        return head + block + tail
    return current.rstrip("\n") + "\n\n" + block + "\n"


def index(root) -> str:
    """The map of all the commands, by area."""
    names = set(root.commands)
    placed = [n for area in AREAS.values() for n in area]
    missing = sorted(names - set(placed))
    if missing:
        raise SystemExit(f"commands without an area in gen_cli_reference.AREAS: {', '.join(missing)}")
    lines = [
        "---",
        "title: Commands",
        "---",
        "",
        NOTE,
        "",
        "# Commands",
        "",
        "Every `fobis` command, by area. Each page lists all the options of the command (generated from the command",
        "line itself); `fobis <command> --help` prints the same. The [fobos file](/fobos/) holds the settings a command",
        "reads from the project, the [user configuration](./configuration) those of the machine.",
        "",
    ]
    for area, commands in AREAS.items():
        lines += [f"## {area}", "", "| Command | What it does |", "|---|---|"]
        for name in commands:
            if name in names:
                summary = _first_line(root.commands[name].help).replace("|", "\\|")
                lines.append(f"| [`{name}`](./{name}) | {summary} |")
        lines.append("")
    return "\n".join(lines)


def outputs() -> dict[Path, str]:
    """Every generated page and its content."""
    import typer

    from fobis.cli._app import app

    root = typer.main.get_command(app)
    found = {REFERENCE / "index.md": index(root)}
    from fobis.UserConfig import _TEMPLATE

    configuration = REFERENCE / "configuration.md"
    text = configuration.read_text()
    head, rest = text.split(CONFIG_BEGIN, 1)
    block = "\n".join([CONFIG_BEGIN, NOTE, "", "```ini", _TEMPLATE.format(path=CONFIG_PATH).rstrip("\n"), "```", ""])
    found[configuration] = head + block + CONFIG_END + rest.split(CONFIG_END, 1)[1]
    fobos = FOBOS.read_text()
    head, rest = fobos.split(KEYS_BEGIN, 1)
    found[FOBOS] = head + keys_section() + rest.split(KEYS_END, 1)[1]
    for name, command in sorted(root.commands.items()):
        path = REFERENCE / f"{name}.md"
        found[path] = page(name, command, path.read_text() if path.is_file() else None)
    return found


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=(__doc__ or "").split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="exit 1 when a page is stale")
    args = parser.parse_args(argv)
    stale = []
    for path, text in outputs().items():
        if not path.is_file() or path.read_text() != text:
            stale.append(path.relative_to(REFERENCE.parent).as_posix())
            if not args.check:
                path.write_text(text)
    for name in stale:
        print(f"{name}: {'stale' if args.check else 'written'}")
    return 1 if args.check and stale else 0


if __name__ == "__main__":
    sys.exit(main())
