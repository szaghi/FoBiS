def _n(count: int, word: str) -> str:
    """*count* *word*s, singular for one (``1 file``, ``3 files``)."""
    return f"{count} {word}" + ("" if count == 1 else "s")


def _listed(items: list[str], limit: int = MAX_LISTED) -> str:
    shown = ", ".join(f"`{i}`" for i in items[:limit])
    return shown + (f" and {len(items) - limit} more" if len(items) > limit else "")


def _counted(items: list[str], what: str) -> str:
    """Up to MAX_LISTED items by name; more are counted per directory (an item is "path ..." or "path: ...")."""
    if len(items) <= MAX_LISTED:
        return _listed(items)
    folders = Counter(os.path.dirname(re.split(r"[ :]", item, maxsplit=1)[0]) or "." for item in items)
    top = sorted(folders.items(), key=lambda kv: (-kv[1], kv[0]))
    shown = ", ".join(f"`{d}/` {n}" for d, n in top[:6]) + (", ..." if len(top) > 6 else "")
    return f"{len(items)} {what} ({shown})"


def _table(header: list[str], rows: list[list[str]]) -> list[str]:
    lines = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    return lines + ["| " + " | ".join(cell.replace("|", "\\|") for cell in row) + " |" for row in rows]


def _modes(facts: ProjectFacts) -> list[str]:
    if not facts.modes:
        return []
    rows = [
        [
            f"`{m.name}`",
            m.compiler,
            m.builds,
            m.flags_summary(),
            ", ".join(m.parallel) or "-",
            " ".join(f"`{d}`" for d in m.defines) or "-",
        ]
        for m in facts.modes
    ]
    out = ["### Modes", "", *_table(["Mode", "Compiler", "Builds", "Flags", "Parallel", "Defines"], rows), ""]
    out += [
        f"Without `--mode` FoBiS uses the first mode, `{facts.default_mode}`. "
        "`fobis introspect --mode MODE --buildoptions` prints a mode's exact flags.",
        "",
    ]
    if facts.setup:
        out += ["Set up the environment before building (fobos `[verification] setup`, by mode or compiler):", ""]
        out += [f"- `{name}`: `{command}`" for name, command in facts.setup.items()]
        out.append("")
    return out


def _commands(facts: ProjectFacts) -> list[str]:
    mode = f" --mode {facts.default_mode}" if facts.default_mode else ""
    out = ["### Commands", ""]
    if facts.dependencies:
        out.append(f"- Dependencies: `fobis fetch` (into `{facts.deps_dir}`) before the first build.")
    out.append(f"- Build: `fobis build{mode}`; on failure `fobis build --json` lists the located diagnoses.")
    if facts.tests:
        out.append(
            f"- Tests ({_n(len(facts.tests), 'program')} in `{facts.test_dir}/`): `fobis test`; one test: "
            "`fobis test --filter NAME`."
        )
    if facts.doctest_modules:
        out.append(f"- Doctests (in the comments of {_n(len(facts.doctest_modules), 'file')}): `fobis doctests`.")
    out.append("- Runtime checks on any mode: add `--shadow checks` to build, run or test.")
    out.append("- Lint: `fobis lint`; only the lines you changed: `fobis review`.")
    if facts.lint:
        settings = "; ".join(
            f"{key} {' '.join(value) if isinstance(value, list) else value}" for key, value in facts.lint.items()
        )
        out.append(f"  The fobos `[lint]` section sets: {settings}.")
    out.append(
        "- Questions about the code, instead of grep: `fobis query callers NAME` (also `callees`, `uses MODULE`, "
        "`writers VAR`, `readers VAR`, `defines NAME`, `interface NAME`, `region FILE:LINE`, `device VAR`, `mpi`)."
    )
    out += [f"- `fobis rule --ex {name}`" + (f": {text}" if text else "") for name, text in facts.rules.items()]
    return [*out, ""]


def _verification(facts: ProjectFacts) -> list[str]:
    out = ["### Verifying a change", ""]
    if not facts.cases:
        return [
            *out,
            "No case is declared, so tests are the only check of results. Cases declared in the fobos "
            "(`[case:NAME]`, see `fobis case --help`) let `fobis verify` and `fobis diff-run` compare results.",
            "",
        ]
    out += [
        "Each case's quantities are compared with its committed reference in "
        f"`{facts.references_dir}/`: run `fobis verify` after a change. A refactoring must leave every case "
        "equivalent: `fobis diff-run` runs them on HEAD and on the working tree. Never update a reference "
        "(`fobis verify --update`) to make a failing case pass: a reference changes only when the new result is "
        "shown to be right.",
        "",
    ]
    rows = []
    for case in facts.cases:
        where = [f"mode `{case['mode']}`"] if case["mode"] else []
        where += [f"{case['ranks']} ranks"] if case["ranks"] else []
        where += [f"{case['threads']} threads"] if case["threads"] else []
        tolerance = "; ".join(f"{q}: {t}" for q, t in case["tolerance"].items()) or "exact"
        assess = ", ".join(case["assess"])
        if case["budgets"]:
            assess += f" (budgets: {'; '.join(case['budgets'])})"
        rows.append(
            [
                f"`{case['name']}`",
                f"`{case['runs']}`" + (f" ({', '.join(where)})" if where else ""),
                ", ".join("every `name = value` line" if q == "*" else q for q in case["quantities"]) or "-",
                tolerance,
                "yes" if case["reference"] else "**missing**",
                f"`fobis assess {case['name']}`: {assess}" if assess else "-",
            ]
        )
    return [*out, *_table(["Case", "Runs", "Quantities", "Tolerance", "Reference", "Assessment"], rows), ""]


def _code(facts: ProjectFacts) -> list[str]:
    out = ["### Code facts", ""]
    analysed = sum(facts.files.values())
    scope = f" (mode `{facts.analysed_mode}`)" if facts.analysed_mode else ""
    if analysed:
        by_ext = ", ".join(f"{n} `{ext}`" for ext, n in facts.files.items())
        out.append(
            f"- Sources{scope}: {_listed(facts.sources)}; {_n(analysed, 'file')} ({by_ext}), {_n(len(facts.modules), 'module')}."
        )
    else:
        out.append(f"- Sources{scope}: {_listed(facts.sources)}; no Fortran file found.")
    if facts.programs:
        out.append(f"- Programs: {_counted(facts.programs, 'programs')}.")
    if facts.dependencies:
        deps = ", ".join(f"{n} ({spec})" for n, spec in facts.dependencies.items())
        out.append(f"- Dependencies (fobos `[dependencies]`): {deps}. Change them upstream, not here.")
    for kinds in facts.kinds:
        parts = []
        for kind, count in list(kinds.counts.items())[:6]:
            details = [f"{kinds.digits[kind]} digits"] if kind in kinds.digits else []
            details += [f"from `{kinds.origins[kind]}`"] if kind in kinds.origins else []
            parts.append(f"`{kind}` {count}" + (f" ({', '.join(details)})" if details else ""))
        more = ", ..." if len(kinds.counts) > 6 else ""
        out.append(f"- `{kinds.type}` declarations by kind: {', '.join(parts)}{more}.")
    if facts.no_implicit_none:
        out.append(f"- Units without `implicit none`: {_counted(facts.no_implicit_none, 'units')}.")
    elif analysed:
        out.append("- Every module, program and external procedure has `implicit none`.")
    parallel = []
    if facts.openmp_files:
        parallel.append(f"OpenMP directives in {_n(facts.openmp_files, 'file')}")
    if facts.openacc_files:
        parallel.append(f"OpenACC directives in {_n(facts.openacc_files, 'file')}")
    if facts.device_variables:
        parallel.append(f"{_n(facts.device_variables, 'module variable')} declared on the device")
    if facts.mpi:
        via = ", ".join(f"`{m}` in {_n(n, 'file')}" for m, n in facts.mpi.items())
        parallel.append(f"MPI through {via} ({_n(facts.mpi_calls, 'MPI call')}: `fobis query mpi`)")
    if parallel:
        out.append("- Parallelism: " + "; ".join(parallel) + ".")
    return [*out, ""]


def render(facts: ProjectFacts) -> str:
    """The generated block, markers included: the same facts always give the same bytes."""
    title = f"## Building and checking {facts.name}" if facts.name else "## Building and checking this project"
    out = [BEGIN, NOTE, "", title, ""]
    if facts.summary:
        out += [facts.summary.rstrip(".") + ".", ""]
    out += [
        "The build tool is FoBiS (`fobis`): it resolves the module dependencies itself, so there is no makefile "
        "to edit. Build settings live in the `fobos` file, one section per mode. Every command below accepts "
        "`--json`; with it, stdout holds only the JSON document.",
        "",
    ]
    out += _modes(facts) + _commands(facts) + _verification(facts) + _code(facts)
    out += [
        "### MCP",
        "",
        "The same facts and checks are MCP tools: `claude mcp add fobis -- fobis mcp` (any MCP client: command "
        "`fobis mcp` over stdio).",
        END,
    ]
    return "\n".join(out) + "\n"


