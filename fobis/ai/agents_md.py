def current_block(text: str) -> str | None:
    """The generated block of *text*, markers included (with its newline); None without one."""
    begin, end = text.find(BEGIN), text.find(END)
    if begin < 0 and end < 0:
        return None
    if begin < 0 or end < begin or text.count(BEGIN) > 1 or text.count(END) > 1:
        raise AgentsMdError("the fobis:begin/end agents-md markers are unbalanced or repeated")
    return text[begin : end + len(END)] + "\n"


def updated(text: str | None, block: str, title: str) -> str:
    """*text* with its block replaced by *block*, appended when it has none; a new file when *text* is None."""
    if text is None:
        return f"# {title}\n\n{block}"
    old = current_block(text)
    if old is None:
        return text.rstrip("\n") + "\n\n" + block
    begin = text.find(BEGIN)
    end = text.find(END) + len(END)
    rest = text[end:].lstrip("\n")
    return text[:begin] + block + ("\n" + rest if rest else "")


def status(path: str, block: str) -> tuple[str, str]:
    """(status, unified diff) of *path* against *block*: current, stale, no-block or missing."""
    if not os.path.isfile(path):
        return "missing", ""
    with open(path, encoding="utf-8") as fh:
        old = current_block(fh.read())
    if old is None:
        return "no-block", ""
    if old == block:
        return "current", ""
    diff = difflib.unified_diff(
        old.splitlines(keepends=True), block.splitlines(keepends=True), f"{path} (file)", f"{path} (generated)"
    )
    return "stale", "".join(diff)


def write(path: str, block: str, title: str) -> str:
    """Write *block* into *path* (atomically): created, updated, appended (the file had no block) or unchanged."""
    text = None
    if os.path.isfile(path):
        with open(path, encoding="utf-8") as fh:
            text = fh.read()
    new = updated(text, block, title)
    if new == text:
        return "unchanged"
    action = "created" if text is None else "appended" if current_block(text) is None else "updated"
    tmp = path + ".fobis-tmp"
    with open(tmp, "w", encoding="utf-8") as fh:
        fh.write(new)
    os.replace(tmp, path)
    return action
