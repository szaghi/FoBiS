"""agents_md.py — the project's instructions for coding agents (``AGENTS.md``), generated from facts.

Everything in the generated block comes from the repository alone — the fobos and the tracked sources — never
from the machine (installed compilers, fetched dependencies, build directories): ``fobis agents-md --check`` gives
the same answer on a laptop and in CI. The block lives between two markers; the rest of the file is the user's and
is never touched.
"""

from __future__ import annotations

import difflib
import os
import re
import subprocess
from collections import Counter
from dataclasses import asdict, dataclass, field
from typing import Any

BEGIN = "<!-- fobis:begin agents-md -->"
END = "<!-- fobis:end agents-md -->"
NOTE = (
    "<!-- Generated by `fobis agents-md` from the fobos and the sources: regenerate it, do not edit it. "
    "Text outside the fobis:begin/end markers is yours and is kept. -->"
)
MAX_LISTED = 12  # programs, sources, units listed by name before "and N more"

_PARALLEL_FLAGS = (
    ("OpenMP", re.compile(r"^(-f?openmp|-qopenmp|-mp(=\S*)?|-qsmp\S*)$")),
    ("OpenACC", re.compile(r"^(-f?openacc|-acc(=\S*)?)$")),
    ("CUDA Fortran", re.compile(r"^(-cuda|-Mcuda\S*)$")),
    ("coarrays", re.compile(r"^(-f?coarray(=\S*)?)$")),
)
_DOCTEST = re.compile(r"^\s*!.```fortran")  # Doctest.py's opening line of a doctest
_TYPE = re.compile(r"^\s*(real|integer|complex|logical|double\s*precision)\s*(?:\*\s*(\d+)|\((.*)\))?", re.I)


class AgentsMdError(Exception):
    """The target file cannot be updated (unbalanced or repeated markers)."""


# ── facts ──────────────────────────────────────────────────────────────────────


@dataclass
class ModeFacts:
    """What a fobos mode builds and how."""

    name: str
    compiler: str
    builds: str
    build_dir: str
    optimisation: int
    debug: bool
    checks: bool
    parallel: list[str]
    defines: list[str]

    def flags_summary(self) -> str:
        parts = [f"-O{self.optimisation}"]
        if self.debug:
            parts.append("debug info")
        if self.checks:
            parts.append("runtime checks")
        return ", ".join(parts)


@dataclass
class KindFacts:
    """The kinds used by the declarations of one intrinsic type."""

    type: str  # real, integer, complex, logical
    counts: dict[str, int]  # kind (or "default") -> declarations, most used first
    origins: dict[str, str] = field(default_factory=dict)  # kind -> module defining or exporting it
    digits: dict[str, int] = field(default_factory=dict)  # real kind -> decimal precision


@dataclass
class ProjectFacts:
    """Everything the generated block says, computed from the fobos and the sources."""

    name: str = ""
    summary: str = ""
    default_mode: str = ""
    modes: list[ModeFacts] = field(default_factory=list)
    analysed_mode: str = ""
    sources: list[str] = field(default_factory=list)
    files: dict[str, int] = field(default_factory=dict)  # extension -> count
    modules: list[str] = field(default_factory=list)
    programs: list[str] = field(default_factory=list)  # "path (name)"
    no_implicit_none: list[str] = field(default_factory=list)
    kinds: list[KindFacts] = field(default_factory=list)
    openmp_files: int = 0
    openacc_files: int = 0
    mpi: dict[str, int] = field(default_factory=dict)  # mpi_f08 / mpi / mpif.h -> files
    mpi_calls: int = 0
    device_variables: int = 0
    test_dir: str = ""
    tests: list[str] = field(default_factory=list)
    doctest_modules: list[str] = field(default_factory=list)
    cases: list[dict] = field(default_factory=list)
    references_dir: str = ""
    setup: dict[str, str] = field(default_factory=dict)
    lint: dict[str, Any] = field(default_factory=dict)
    deps_dir: str = ""
    dependencies: dict[str, str] = field(default_factory=dict)
    rules: dict[str, str] = field(default_factory=dict)

    def to_dict(self) -> dict:
        return asdict(self)


def _substitute(text: str, variables: dict[str, str]) -> str:
    for var, val in sorted(variables.items(), key=lambda kv: -len(kv[0])):
        text = re.sub(re.escape(var) + r"(?![A-Za-z0-9_])", lambda _m, v=val: v, text)
    return " ".join(text.split())


def parallel_models(cflags: str) -> list[str]:
    """The parallel programming models that compile flags enable: OpenMP, OpenACC, CUDA Fortran, coarrays."""
    flags = cflags.split()
    return [model for model, pattern in _PARALLEL_FLAGS if any(pattern.match(f) for f in flags)]


def mode_facts(fobos: Any) -> list[ModeFacts]:
    """Every mode of a parsed `Fobos` (templates applied by Fobos; ``$variables`` and build profiles here)."""
    from ..Profiles import get_profile_flags
    from .crash import optimisation

    parser = getattr(fobos, "fobos", None)
    if parser is None:
        return []
    names = parser.get("modes", "modes").split() if parser.has_option("modes", "modes") else []
    if not names and parser.has_section("default"):
        names = ["default"]
    variables = getattr(fobos, "local_variables", {}) or {}
    facts = []
    for name in names:
        if not parser.has_section(name):
            continue

        def value(key: str, default: str = "", section: str = name) -> str:
            raw = parser.get(section, key) if parser.has_option(section, key) else default
            return _substitute(raw, variables)

        compiler = value("compiler", "gnu").lower()
        cflags = value("cflags")
        if value("build_profile"):
            cflags = (get_profile_flags(compiler, value("build_profile"))["cflags"] + " " + cflags).strip()
        parallel = parallel_models(cflags)
        for key, model in (("openmp", "OpenMP"), ("openmp_offload", "OpenMP offload"), ("coarray", "coarrays")):
            if value(key).lower() == "true" and model not in parallel:
                parallel.append(model)
        if compiler == "opencoarrays-gnu" and "coarrays" not in parallel:
            parallel.append("coarrays")
        if value("mpi").lower() == "true" or "mpi" in value("fc").lower():
            parallel.append("MPI")
        target, output, mklib = value("target"), value("output"), value("mklib")
        if target and mklib in ("static", "shared"):
            builds = f"{mklib} library `{output or target}` from `{target}`"
        elif target:
            builds = f"program `{output or os.path.splitext(os.path.basename(target))[0]}` from `{target}`"
        else:
            builds = "every program in the sources"
        level, debug, checks = optimisation(compiler, cflags)
        defines = [d for d in value("preproc").split() if d.startswith("-D")]
        facts.append(
            ModeFacts(name, compiler, builds, value("build_dir", "./"), level, debug, checks, parallel, defines)
        )
    return facts


def _kind_of(type_spec: str) -> tuple[str, str] | None:
    """(type, kind) of a declaration's type spec; kind 'default' when none is written."""
    match = _TYPE.match(type_spec)
    if not match:
        return None
    base = match.group(1).lower()
    if base.replace(" ", "") == "doubleprecision":
        return "real", "double precision"
    if match.group(2):
        return base, f"*{match.group(2)}"
    inside = (match.group(3) or "").strip()
    if not inside:
        return base, "default"
    return base, re.sub(r"^kind\s*=\s*", "", inside.split(",")[0].strip())


def kind_facts(units: dict, project: Any) -> list[KindFacts]:
    """The kinds the declarations use (named constants excluded), per type, with the module defining each named
    kind or, failing that, the only module an only-list imports it from."""
    from ..analysis.query import use_names

    counts: dict[str, Counter] = {}
    spelling: dict[str, str] = {}  # lower-case kind -> as first written in the sources
    defined: dict[str, str] = {}
    exported: dict[str, set[str]] = {}
    for file_units in units.values():
        for unit in file_units.walk():
            for decl in unit.decls.values():
                if unit.kind == "module" and "parameter" in decl.attrs and decl.init is not None:
                    defined.setdefault(decl.name, unit.name)
                found = _kind_of(decl.type_spec) if decl.type_spec else None
                if found and "parameter" not in decl.attrs:
                    counts.setdefault(found[0], Counter())[found[1]] += 1
                    if found[1] not in spelling and 0 < decl.line <= len(file_units.source.lines):
                        written = re.search(
                            r"(?<!\w)" + re.escape(found[1]) + r"(?!\w)", file_units.source.lines[decl.line - 1], re.I
                        )
                        spelling[found[1]] = written.group(0) if written else found[1]
            for use in unit.uses:
                for local, original in use_names(use.statement)[0].items():
                    if local == original:
                        exported.setdefault(local, set()).add(use.module)
    facts = []
    for type_name in ("real", "integer", "complex", "logical"):
        counter = counts.get(type_name)
        if not counter:
            continue
        ordered = sorted(counter.items(), key=lambda kv: (-kv[1], kv[0]))
        named, origins, digits = {}, {}, {}
        for kind, count in ordered:
            shown = spelling.get(kind, kind)
            named[shown] = count
            if kind in defined:
                origins[shown] = defined[kind]
            elif len(exported.get(kind, ())) == 1:
                origins[shown] = next(iter(exported[kind]))
            if type_name in ("real", "complex") and re.fullmatch(r"[a-z_]\w*|\d+", kind):
                precision = project.real_precision(kind)
                if precision:
                    digits[shown] = precision
        facts.append(KindFacts(type_name, named, origins, digits))
    return facts


def _relative(path: str, root: str) -> str:
    return os.path.relpath(path, root).replace(os.sep, "/")


def _tracked(root: str) -> list[str]:
    """Files git tracks or would track under *root* (normalised paths); [] outside a repository."""
    done = subprocess.run(
        ["git", "-C", root, "ls-files", "-z", "--cached", "--others", "--exclude-standard"],
        capture_output=True,
        text=True,
    )
    if done.returncode != 0:
        return []
    return [os.path.normpath(os.path.join(root, f)) for f in done.stdout.split("\0") if f]


def project_files(discovered: list[str], root: str, deps_dir: str) -> list[str]:
    """The mode's sources that belong to the repository: not ignored by git, not under the dependencies dir."""
    tracked = set(_tracked(root))
    deps = os.path.normpath(os.path.join(root, deps_dir)) if deps_dir else ""
    kept = []
    for path in discovered:
        norm = os.path.normpath(path)
        if deps and (norm == deps or norm.startswith(deps + os.sep)):
            continue
        if tracked and norm not in tracked:
            continue
        kept.append(path)
    return kept


def collect(configuration: Any, files: list[str], root: str = ".") -> ProjectFacts:
    """The facts of the project of *configuration* (a `FoBiSConfig`), analysing *files* (`project_files`)."""
    from ..analysis import parse_defines
    from ..analysis.query import CodeGraph, query
    from ..fobis import _merged_preproc_flags
    from ..lint import lint_files
    from ..TestRunner import discover_tests
    from ..verification import load_cases
    from ..verification.assess import load_spec
    from ..verification.case import load_settings

    fobos = configuration.fobos
    cliargs = configuration.cliargs
    parser = getattr(fobos, "fobos", None)
    facts = ProjectFacts()
    if parser is not None:
        facts.name = fobos.get_project_info().get("name", "") or ""
        if parser.has_option("project", "summary"):
            facts.summary = " ".join(parser.get("project", "summary").split())
        facts.modes = mode_facts(fobos)
        facts.default_mode = facts.modes[0].name if facts.modes else ""
        facts.analysed_mode = fobos.mode or ""
        facts.dependencies = dict(sorted(fobos.get_dependencies().items()))
        facts.deps_dir = fobos.get_deps_dir() if facts.dependencies else ""
        facts.lint = {k: v for k, v in fobos.get_lint_config().items() if v}
        for section in parser.sections():
            if section.startswith("rule-"):
                facts.rules[section[5:]] = " ".join(parser.get(section, "help", fallback="").split())
        facts.rules = dict(sorted(facts.rules.items()))
        settings = load_settings(fobos)
        facts.setup = dict(sorted(settings.setup.items()))
        cases = load_cases(fobos)
        if cases:
            facts.references_dir = settings.references_dir
        for case in sorted(cases.values(), key=lambda c: c.name):
            spec = load_spec(fobos, case.name) if parser.has_section(f"assess:{case.name}") else None
            reference = os.path.join(root, settings.references_dir, f"{case.name}.json")
            facts.cases.append(
                {
                    "name": case.name,
                    "description": case.description,
                    "runs": case.target or " ".join(case.command),
                    "mode": case.mode or "",
                    "ranks": case.ranks,
                    "threads": case.threads,
                    "quantities": sorted(p.name for p in case.probes),
                    "tolerance": dict(sorted(case.tolerance.items())),
                    "reference": os.path.isfile(reference),
                    "assess": sorted(spec.families) if spec else [],
                    "budgets": [b.text() for b in spec.budgets] if spec else [],
                }
            )
        test_dir = fobos.get_test_config()["test_dir"]
        if os.path.isdir(os.path.join(root, test_dir)):
            tracked = set(_tracked(root))
            facts.test_dir = test_dir
            facts.tests = sorted(
                _relative(t["source"], root)
                for t in discover_tests(os.path.join(root, test_dir))
                if not tracked or os.path.normpath(t["source"]) in tracked
            )
    facts.sources = sorted({_relative(s, root) for s in cliargs.src})
    analysed = lint_files(files, [], defines=parse_defines(_merged_preproc_flags(cliargs)))
    units = analysed.units
    facts.files = dict(sorted(Counter(os.path.splitext(p)[1] for p in units).items()))
    # a file included by another one belongs to its includer's scope (implicit none, module): no units of its own
    included = {os.path.basename(name) for f in units.values() for _, name in f.source.includes}
    for path, file_units in sorted(units.items()):
        rel = _relative(path, root)
        sentinels = {s.sentinel for s in file_units.source.statements if getattr(s, "sentinel", None)}
        facts.openmp_files += "omp" in sentinels
        facts.openacc_files += "acc" in sentinels
        if any(_DOCTEST.search(line) for line in file_units.source.lines):
            facts.doctest_modules.append(rel)
        for unit in file_units.units if os.path.basename(path) not in included else ():
            if unit.kind == "module":
                facts.modules.append(unit.name)
            elif unit.kind == "program":
                facts.programs.append(f"{rel} ({unit.name})")
            if unit.kind in ("module", "submodule", "program", "subroutine", "function") and not unit.implicit_none:
                facts.no_implicit_none.append(f"{rel}: {unit.kind} {unit.name}")
        mpi = {u.module for unit in file_units.walk() for u in unit.uses if u.module in ("mpi", "mpi_f08")}
        if any(os.path.basename(name).lower() == "mpif.h" for _, name in file_units.source.includes):
            mpi.add("mpif.h")
        for name in mpi:
            facts.mpi[name] = facts.mpi.get(name, 0) + 1
    facts.mpi = dict(sorted(facts.mpi.items()))
    facts.modules.sort()
    facts.kinds = kind_facts(units, analysed.project)
    facts.device_variables = len(getattr(analysed.project, "device_variables", {}) or {})
    if facts.mpi:
        facts.mpi_calls = len(query(CodeGraph(units, analysed.project), "mpi").items)
    return facts


